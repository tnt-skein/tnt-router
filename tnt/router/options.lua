--- Проверка настроек: опечатка обязана обнаружиться при загрузке.
---
--- Настройки роутера и настройки раздачи проверяются одинаково и по одной
--- причине: их пишут кодом, а не вводят руками, и негодная настройка — это
--- промах разработчика. Обнаружиться он обязан там, где его видит
--- разработчик — при объявлении маршрута, — а не ночью, когда его видит
--- дежурный: `missing = 'строка'` доживает до первого промаха по файлу
--- и срывается обращением к строке как к функции внутри боевого запроса.
---
--- Проверка живёт отдельным модулем, а не в каждом месте своя: два
--- одинаковых куска в одном пакете однажды расходятся, и расходятся молча.
---
--- Уровень вины приходит от того, кто проверку позвал, и считается как
--- у `error`: 1 — сама проверка. Без него отказ показывал бы сюда,
--- в пакет, а у одной функции выходило бы два места на один класс ошибок:
--- адрес приложения винит строку `router.new`, а `prefix` рядом с ним —
--- эту. Поэтому уровень обязателен: забытый, он вернул бы ровно такое
--- второе место.

local Module = {}

--- Как назвать вид настройки в тексте отказа.
local KINDS = {
    string = 'строкой',
    table = 'таблицей',
    ['function'] = 'функцией',
    number = 'числом',
    boolean = 'true или false',
}

--- Настройка нужного вида или отказ.
---@param value any
---@param kind string Тип из type()
---@param fallback any Чем заменить отсутствие
---@param name string Имя настройки
---@param level integer Уровень вины, как у `error`: 1 — эта функция
---@return any
function Module.expected(value, kind, fallback, name, level)
    if value == nil then
        return fallback
    end

    if type(value) ~= kind then
        error(
            ('настройка «%s» должна быть %s, а не %s'):format(name, KINDS[kind], type(value)),
            level
        )
    end

    return value
end

--- Настройка числом больше нуля или отказ.
---
--- Отдельно от `expected` потому, что вид тут — половина дела: предел
--- размера или кусок в ноль байт проходят проверку типа и срываются
--- уже в ответе — пустым телом вместо файла, который лежит на месте.
---@param value any
---@param fallback number Чем заменить отсутствие
---@param name string Имя настройки
---@param level integer Уровень вины, как у `error`: 1 — эта функция
---@return number
function Module.positive(value, fallback, name, level)
    -- Проверка вида зовётся отсюда, и вина у неё кадром дальше.
    local number = Module.expected(value, 'number', fallback, name, level + 1)

    if number <= 0 then
        error(
            ('настройка «%s» должна быть больше нуля, а не %s'):format(name, number),
            level
        )
    end

    return number
end

return Module
