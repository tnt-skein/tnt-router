--- Место ошибки объявления: строка того, кто позвал вход роутера.
---
--- Маршрут без обработчика, опечатка в шаблоне, незнакомое ограничение,
--- маршрут, объявленный дважды, незнакомое имя слоя — промах в строке
--- приложения, и отказ обязан указывать туда. Строка внутри пакета
--- отправила бы искать ошибку в нём.
---
--- Но проверки стоят глубоко, и кадров от входа до них разное число:
--- шаблон разбирается участками, дерево раскладывает необязательные
--- участки на варианты, слои собирает соседний пакет. Уровень `error`,
--- посчитанный на месте проверки, от этого всякий раз разный. Поэтому
--- проверки бросают текст без места (`fail.raise` из `tnt-must`), а место
--- приписывает вход: зовёт свою работу под `pcall` и бросает отказ заново
--- уровнем того, кто позвал сам вход.
---
--- Функция, которая винит своего вызывающего (`error(текст, 2)`), под
--- `pcall` винит сам `pcall` — кадр C без строки, — и её отказ выходит
--- без места. Этим вход и пользуется, когда зовёт такую функцию своей
--- работой. А чужую функцию посреди работы — сборку слоёв, разрешение
--- обработчика — зовут через `bare`: позванная напрямую, она винила бы
--- строку пакета, и вход приписал бы к отказу второе место.
---
--- Брошенное не строкой уходит дальше тем же значением: у таблицы
--- и у объекта ошибки места не бывает, и `error` его не приписывает.

local fail = require('tnt.must.fail')

local Module = {}

--- Зовёт работу входа и винит в её броске того, кто позвал вход.
---
--- Зовут её отдельным предложением или присваиванием, а не хвостом:
--- хвостовой вызов снял бы кадр входа со стека, и вина ушла бы на кадр
--- дальше — к тому, кто позвал вызывающего.
---@generic R
---@param work fun(...: any): R Работа входа: бросает текст без места
---@param ... any Аргументы работы
---@return R
function Module.call(work, ...)
    local done, result = pcall(work, ...)

    if done then
        return result
    end

    -- Первый уровень — эта функция, второй — вход, третий — тот, кто
    -- позвал вход.
    error(result, 3)
end

--- Зовёт чужую функцию посреди работы входа так, что её бросок выходит
--- без места.
---
--- Место отказу припишет вход. Чужая функция, винящая своего вызывающего,
--- под `pcall` винит кадр без строки; бросок уровнем 1 своё место
--- сохранит — это строка той функции, и искать там есть что.
---@generic R
---@param work fun(...: any): R Чужая функция объявления
---@param ... any Её аргументы
---@return R
function Module.bare(work, ...)
    local done, result = pcall(work, ...)

    if done then
        return result
    end

    -- `return` — для анализатора типов: что `raise` не возвращается,
    -- он через границу модуля не видит.
    return fail.raise(result)
end

return Module
