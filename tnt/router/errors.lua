--- Отказы роутера: 404, 405, 500 и отказы тела запроса — и ничего сверх того.
---
--- Обработка ошибок целиком — дело отдельного пакета: у приложения один
--- вид отказа на все слои, и роутеру решать его за всех не по чину. Здесь
--- ровно тот минимум, которым роутер обязан ответить сам, даже когда
--- рядом ничего больше не поставили. Свой обработчик подставляется
--- вызовом `router.on_error`, и тогда этот код не зовётся вовсе.
---
--- Наружу не уходит ни текст чужого отказа, ни стек, ни имя обработчика:
--- в теле только код, общая фраза и опознаватель происшествия. По нему
--- запись находится в журнале — подробности лежат там. Всё остальное
--- в теле ответа — это подсказка тому, кто ищет уязвимость, и мусор
--- тому, кто просто работает.
---
--- Опознаватель пишется по договору, общему с пакетом отказов
--- приложения: восемь случайных знаков азбуки Крокфорда двумя группами,
--- `4KJ7-QW9M`. Вид один на оба пакета, потому что их номера стоят в одном
--- поле одного ответа, и человек диктует их дежурному по телефону —
--- а `uuid` в тридцать шесть знаков вслух не читается. Азбука берётся
--- у `tnt-id`, а сам пакет отказов роутеру не нужен: свой минимум роутер
--- отдаёт и без него.
---
--- Ответ в JSON: роутер обслуживает и API, и панель, а панель читает
--- отказы разбором тела. Кому нужен другой вид — подставляет свой
--- обработчик, и это одна строка.
---
--- Сам отказ — договор, общий с пакетом отказов приложения: таблица
--- с числовым `status` и необязательными `message`, `code`, `incident`,
--- `headers`. Это и есть то, что уходит в `router.on_error`, и по этому
--- же договору пакет отказов узнаёт отказ роутера своим, а не внутренней
--- поломкой. Отсюда два требования к этому модулю. Слово для человека
--- кладётся в сам отказ, а не только в ответ: подставивший чужой
--- обработчик иначе получил бы «внутренняя ошибка» вместо «нет такого
--- адреса». Заголовок `Allow` при 405 кладётся туда же: RFC 9110 требует
--- его от ответа, а не от того, кто ответ собрал, — и при подмене
--- обработчика заголовок, живущий только здесь, потерялся бы молча.

local digest = require('digest')
local json = require('json')

local crockford = require('tnt.id.crockford')
local external = require('tnt.external')

local Module = {}

--- Что сказать человеку. Общими словами и одинаково для всех:
--- по разным фразам на один код отказа узнают, что внутри.
local MESSAGES = {
    [400] = 'запрос не разобран',
    [404] = 'нет такого адреса',
    [405] = 'этот способ здесь не поддерживается',
    [408] = 'тело запроса не пришло вовремя',
    [411] = 'запросу с телом нужен заголовок Content-Length',
    [413] = 'тело запроса слишком велико',
    [500] = 'внутренняя ошибка',
}

--- Тип содержимого отказа.
local CONTENT_TYPE = 'application/json; charset=utf-8'

--- Границы статуса, по которым отказ узнаётся отказом.
---
--- Только 4xx и 5xx: таблица с успешным статусом — это ответ, и принять
--- её за отказ значило бы молча превратить промах вызывающего в готовый
--- ответ клиенту.
local MIN_STATUS = 400
local MAX_STATUS = 599

--- Сколько знаков в опознавателе происшествия и по сколько в группе.
---
--- Числа из общего договора отказов: триллион сочетаний — с запасом на все
--- происшествия, пока живёт журнал, и восемь знаков ещё диктуются
--- без ошибок.
local INCIDENT_LENGTH = 8
local INCIDENT_GROUP = 4

--- Средства снаружи: случайность для опознавателя происшествия.
---
--- Случайность ядра, а не `math.random`: тот после одинаковой затравки
--- выдаёт на двух узлах одни и те же номера, и номер из ответа привёл бы
--- к записи чужого узла. И не ULID из `tnt-id`: время в старших знаках
--- выдало бы снаружи, когда узел отказал, а два номера одной миллисекунды —
--- сколько опознавателей узел выдал между ними.
local DEFAULTS = {
    random = digest.urandom,
}

local source = external.install(Module, DEFAULTS)

---@class TntRouterFailure
---@field status integer Код отказа
---@field message string|nil Слово для человека; его роутер говорит сам, по статусу
---@field code string|nil Код отказа: из каталога приложения либо у отказа подписанной ссылки
---@field reason any Что пришло из обработчика; наружу не уходит
---@field incident string|nil Опознаватель; он есть у отказа, о котором написано в журнал
---@field headers table<string, string>|nil Заголовки ответа: Allow при 405

--- Поле договора, если оно той породы, какую договор обещает.
---
--- Таблица или число на месте слова уехали бы клиенту как есть, а сказать
--- человеку им нечего.
---@param value any
---@return string|nil
local function worded(value)
    if type(value) ~= 'string' then
        return nil
    end

    return value
end

--- Новый опознаватель происшествия.
---
--- Каждый случайный байт становится знаком по своим пяти младшим битам:
--- на каждый из тридцати двух знаков приходится ровно восемь значений
--- байта, и перекоса нет.
---@return string
function Module.incident()
    local letters = crockford.spell(source().random(INCIDENT_LENGTH))

    return crockford.group(letters, INCIDENT_GROUP)
end

--- Способы, которые адрес принимает на самом деле: перечень для `Allow`.
---
--- GET всегда идёт вместе с HEAD, а OPTIONS роутер обслуживает сам:
--- назвать в `Allow` только объявленное значило бы соврать про оба,
--- а по этому перечню клиент решает, чем ходить.
---@param allowed string[] Способы, объявленные на адресе
---@return string[]
function Module.offered(allowed)
    local names = {}
    local seen = {}

    --- Добавляет способ, если его ещё не называли.
    ---@param name string
    local function add(name)
        if seen[name] then
            return
        end

        seen[name] = true

        table.insert(names, name)
    end

    add('OPTIONS')

    for _, name in ipairs(allowed) do
        add(name)
    end

    if seen.GET then
        add('HEAD')
    end

    table.sort(names)

    return names
end

--- Что сказать человеку об отказе с таким статусом.
---
--- Незнакомый статус описывается как поломка: свои коды роутера перечислены
--- выше, и любой другой означает, что отказ собрал не он.
---@param status integer
---@return string
function Module.message_of(status)
    return MESSAGES[status] or MESSAGES[500]
end

--- Отказ границы HTTP, если причина им и была.
---
--- Договор читается в обе стороны: по нему роутер отдаёт свой отказ
--- наружу, и по нему же узнаёт чужой — тот, что вернул обработчик парой
--- `nil, err`. Обработчик, назвавший свой статус, при нём и остаётся:
--- решать за него, что его «клиента больше нет» — поломка узла, роутеру
--- не по чину, а прежний ответ был именно такой, 500.
---
--- Признак один и он явный — число в `status`. Ни по виду строки, ни
--- по набору полей роутер не гадает: `{ status = 'ok' }` и запись работы
--- `{ status = 1 }` отказом не считаются.
---@param reason any Что вернул обработчик вторым значением
---@return TntRouterFailure|nil
function Module.refusal_of(reason)
    if type(reason) ~= 'table' then
        return nil
    end

    local status = reason.status

    if type(status) ~= 'number' or status % 1 ~= 0 then
        return nil
    end

    if status < MIN_STATUS or status > MAX_STATUS then
        return nil
    end

    ---@type TntRouterFailure
    local declared = {
        -- Целость числа проверена выше, а вывод типов её не видит.
        status = status --[[@as integer]],
        message = worded(reason.message),
        code = worded(reason.code),
        incident = worded(reason.incident),
        headers = reason.headers,
        -- Причина остаётся причиной: она нужна записи в журнале, и только ей.
        reason = reason,
    }

    return declared
end

--- Строит отказ.
---
--- Отказ первым аргументом, запрос вторым: обработчик отказов пишется про
--- отказ, а запрос ему нужен не всегда — этому, например, не нужен вовсе.
---@param failure TntRouterFailure
---@param _request TntRouterRequest|nil Запрос; этому отказу он не нужен
---@return table response
function Module.respond(failure, _request)
    local status = failure.status
    local headers = {}

    -- Заголовки берутся из самого отказа: `Allow` при 405 обязателен
    -- по RFC 9110, и требует его RFC от ответа, а не от того, кто ответ
    -- собрал. Живи он только здесь — подменивший обработчик потерял бы
    -- его молча.
    for name, value in pairs(failure.headers or {}) do
        headers[name] = value
    end

    headers['content-type'] = CONTENT_TYPE

    return {
        status = status,
        headers = headers,
        body = json.encode({
            error = {
                status = status,
                message = failure.message or Module.message_of(status),
                -- Код есть у отказа из каталога приложения и у отказа
                -- подписанной ссылки (`tnt.router.signed`): у отказов,
                -- которые собирает этот модуль, поля не будет.
                code = failure.code,
                incident = failure.incident,
            },
        }),
    }
end

--- Последний аргумент: упал сам обработчик отказов.
---
--- Тело собрано строкой, а не сборщиком JSON: к этой ветке приходят
--- тогда, когда сломалось то, что должно было работать, и звать здесь
--- ещё что-нибудь значит рисковать вторым падением подряд — а на него
--- ответить уже нечем.
---@param incident string
---@return table
function Module.last_resort(incident)
    return {
        status = 500,
        headers = { ['content-type'] = CONTENT_TYPE },
        body = ('{"error":{"status":500,"incident":"%s"}}'):format(incident),
    }
end

return Module
