--- Откуда раздача берёт байты: набор в памяти и каталог на диске.
---
--- Панель приезжает упакованной в модуль (`bundle`), а собранные стили
--- и сценарии приложения лежат на диске (`root`) и пересобираются
--- на каждую правку. Обоим нужен один и тот же ответ: содержимое, размер,
--- метка версии и время правки, — и складывать его в двух местах значит
--- однажды разойтись в том, что считается файлом.
---
--- На диске отдаются только обычные файлы. Каталог, сокет, устройство
--- и **символьная ссылка** не отдаются вовсе: `realpath` в `fio` нет,
--- и отличить ссылку внутрь раздачи от ссылки на `/etc/passwd` нечем,
--- а раздача, которая ходит по ссылкам, выносит наружу то, чего в её
--- каталоге нет. Поэтому путь опрашивается без раскрытия ссылки
--- (`fs.stat` с `follow = false`). Каталог-ссылка на пути
--- (`public/build` → чужой каталог) при этом остаётся: её завёл владелец
--- узла, а не клиент, — и об этом сказано в `docs/router.md`.
---
--- Большой файл в память не читается. Предел задаётся настройкой:
--- файл до него читается строкой и получает метку по содержимому,
--- файл сверх — отдаётся кусками читателем `tnt-fs`, а метка ему
--- считается по размеру и времени правки. Читать гигабайт ради crc32
--- значит держать этот гигабайт в памяти узла — ровно то, ради чего
--- ответ и режется на куски.

local fs = require('tnt.fs')

local external = require('tnt.external')

local Module = {}

--- Средства снаружи: подсчёт метки.
---
--- Подсчёт метки вынесен во внешние зависимости ради проверки: снимок набора заведён,
--- чтобы метка считалась один раз на файл, а не на запрос, и проверка
--- обязана видеть число подсчётов, а не верить комментарию.
local DEFAULTS = {
    digest = function()
        return require('digest')
    end,
}

local source = external.install(Module, DEFAULTS)

---@class TntRouterFile
---@field body string|nil Содержимое, когда оно уже в памяти
---@field path string|nil Путь на диске, когда файл читается кусками
---@field size integer Размер, байт
---@field tag string Метка версии
---@field modified integer|nil Время правки, секунды эпохи; у набора его нет

--- Метка версии содержимого.
---
--- В кавычках: по RFC 9110 метка без них — не метка, и разборчивый
--- посредник такой заголовок выбросит.
---@param body string
---@return string
function Module.tag_of(body)
    return ('"%08x"'):format(source().digest().crc32(body))
end

--- Метка версии большого файла: размер и время правки.
---
--- Содержимое такого файла в память не читается вовсе, и считать по нему
--- crc32 значило бы сделать ровно то, чего избегает отдача кусками.
--- Время правки в метке — целыми секундами, поэтому файл, переписанный
--- дважды за одну секунду без смены размера, сохранит прежнюю метку;
--- для собранных стилей и сценариев, у которых отпечаток стоит в имени,
--- это не случается — имя меняется вместе с содержимым.
---
--- Секунды целые уже у `fs.stat`: дробь, которую система хранит
--- (`st_mtim` на Linux), он отбрасывает вниз. С дробью файл выходил бы
--- новее любой даты, которую браузер присылает назад в
--- `If-Modified-Since`, и 304 не приходил бы никогда.
---@param stat TntFsStat
---@return string
local function stamp_of(stat)
    return ('"%x-%x"'):format(stat.size, stat.mtime)
end

--- Снимок набора в памяти: содержимое и метка каждого файла.
---
--- Набор копируется, а не читается потом по ссылке: файл, подменённый
--- в таблице после сборки, отдавался бы со старой меткой, и браузер
--- с прошлой копией получал бы 304 на новое содержимое — то есть
--- не увидел бы его до следующей правки. Копия стоит дёшево: строки
--- в Lua не копируются, копируются ссылки на них.
---
--- Вид каждой записи спрашивается здесь же, как и вид настроек: файл
--- таблицей вместо строки иначе сорвался бы подсчётом метки, а имя
--- числом — список `{ 'app.js' }` вместо набора — молча не нашлось бы
--- ни по одному адресу.
---
--- Отказ винит того, кто объявил раздачу, как и отказ любой другой
--- её настройки: уровень приходит от проверки настроек.
---@param bundle table
---@param level integer Уровень вины, как у `error`: 1 — эта функция
---@return table<string, TntRouterFile>
function Module.snapshot(bundle, level)
    local files = {}

    for name, body in pairs(bundle) do
        if type(name) ~= 'string' then
            error(
                ('имя файла в bundle должно быть строкой, а не %s'):format(type(name)),
                level
            )
        end

        if type(body) ~= 'string' then
            error(
                ('файл «%s» в bundle должен быть строкой, а не %s'):format(name, type(body)),
                level
            )
        end

        files[name] = { body = body, size = #body, tag = Module.tag_of(body) }
    end

    return files
end

--- Куски файла для ответа по кускам.
---
--- Файл открывается сразу, до ответа: исчезнувший между опросом
--- и открытием — это «файла нет», а не 200 с оборванным телом. Открытый
--- файл переживает удаление и уходит целиком. Закрывается он на последнем
--- куске и на отказе; клиент, ушедший посреди выгрузки, оставит его
--- до сборки мусора — закрыть его роутеру негде, обрыв он видит броском.
---
--- Недочитанный файл — отказ парой, а не конец: кончившийся источник
--- сервер закрывает завершающим куском, и клиент принял бы обрезанный
--- файл за целый.
---@param path string
---@param chunk integer Размер куска, байт
---@return (fun(): string|nil, TntFsFailure|nil)|nil chunks Источник кусков; nil — файл не открылся
function Module.chunks(path, chunk)
    local reader = fs.reader(path, { chunk = chunk })

    if reader == nil then
        return nil
    end

    return function()
        return reader:read()
    end
end

--- Файл каталога: сведения и содержимое, если оно влезает в память.
---
--- Отдаются только обычные файлы: каталог, ссылка и устройство — все
--- здесь «файла нет». Ссылка отвергается намеренно, а не за компанию
--- (см. шапку модуля). Путь склеен чертой как есть: имя уже проверено
--- раздачей участками, пустых и точечных участков в нём нет.
---
--- Файл, который не опросился или не прочитался, — тоже «файла нет»,
--- каким бы ни был отказ: клиенту всё равно, чего нет по адресу, а разные
--- ответы на «нет» и «не отдам» рассказывали бы ему об устройстве диска.
---@param root string
---@param name string
---@param in_memory integer Предел чтения в память, байт
---@return TntRouterFile|nil
function Module.from_disk(root, name, in_memory)
    local path = root .. '/' .. name
    local stat = fs.stat(path, { follow = false })

    if stat == nil or stat.kind ~= 'file' then
        return nil
    end

    if stat.size > in_memory then
        return {
            path = path,
            size = stat.size --[[@as integer]],
            tag = stamp_of(stat),
            modified = stat.mtime,
        }
    end

    local body = fs.read(path)

    if body == nil then
        return nil
    end

    -- Размер берётся у прочитанного, а не у `stat`: между вызовами файл
    -- успевают переписать, и длина из `stat` разошлась бы с телом.
    return { body = body, size = #body, tag = Module.tag_of(body), modified = stat.mtime }
end

return Module
